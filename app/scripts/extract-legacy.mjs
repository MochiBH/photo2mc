// Pulls the tested, DOM-free logic out of the previous single-file page into src/lib/legacy.js.
import { readFileSync, writeFileSync } from 'node:fs';
import * as acorn from 'acorn';
const html = readFileSync(new URL('./legacy-page.html', import.meta.url), 'utf8');
const m = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(x => x[1]).sort((a, b) => b.length - a.length)[0];
const want = new Set(`gkey mergeGames parseOpgg gamesFromOpgg cspm rec statsLine labPrompt parseLab norm champOf andList shortName teamFeatures allyFeatures teamPhys pickTop buildKha buildNunu withBought buildNotes gamePlan nunuRole gankOrder gankText sgn clock errText
SNAP RULES DECKS TAGNAME FOES KEYS BRIEF RUNES RUNE_FX ALIAS BOOTS STUCK SLIPPERY ZONE OBJS WHO WHEN CHECKS OPGG OPGG_TOOL OPGG_INPUT GSTORE STORE BSTORE CN`.split(/\s+/));
const ast = acorn.parse(m, { ecmaVersion: 'latest', sourceType: 'script' });
const out = [], names = [];
for (const n of ast.body) {
  if (n.type === 'FunctionDeclaration' && want.has(n.id.name)) { out.push(m.slice(n.start, n.end)); names.push(n.id.name); }
  else if (n.type === 'VariableDeclaration' && n.declarations.some(d => want.has(d.id.name))) { out.push(m.slice(n.start, n.end)); n.declarations.forEach(d => names.push(d.id.name)); }
}
const missing = [...want].filter(w => !names.includes(w));
if (missing.length) throw new Error('missing: ' + missing.join(', '));
const head = `/* Generated by scripts/extract-legacy.mjs from the previous single-file page. Edit there, or move a function out of this file before changing it. */
const BD = window.BUILD || { champs: {}, gold: {}, pulled: '' };
export let bst = null, GAMES = [];
export function setBst(v) { bst = v; }
export function setGames(v) { GAMES = v; }
const esc = s => String(s);
`;
const tail = `\nCN.forEach(n => { CKEY[norm(n)] = n; });\nexport { BD, ${[...new Set(names)].join(', ')} };\n`;
writeFileSync(new URL('../src/lib/legacy.js', import.meta.url), head + out.join('\n') + tail);
console.log('extracted', names.length, 'declarations');
