def glyph(ch):
    g = _GLYPHS.get(ch.upper(), _GLYPHS[" "])
    return np.array([[c == "#" for c in row] for row in g], bool)


def text(s, gap=1, scale=1):
    """-> bool array (7*scale, ...) with True for ink."""
    cols = []
    for i, ch in enumerate(s):
        if i:
            cols.append(np.zeros((7, gap), bool))
        cols.append(glyph(ch))
    a = np.hstack(cols) if cols else np.zeros((7, 0), bool)
    return np.kron(a, np.ones((scale, scale), bool)).astype(bool)
